def recommend_story(message):
    """Simple editorial keyword hint, not a diagnosis. Unknown text uses bridge."""
    text = str(message or '')
    if any(word in text for word in ('休', '疲', '焦ら', 'ゆっくり', 'リラックス')):
        return 'rest'
    if any(word in text for word in ('挑戦', '一歩', '始め', 'チャレンジ', '踏み出')):
        return 'step'
    return 'bridge'
